using System.Collections;
using UnityEngine;

// ??? ??????? ?? ??? ???? ????? UpgradeIndicator ????
public class UpgradeAvailableFX : MonoBehaviour
{
    [Header("Refs")]
    [SerializeField] private Light glowLight;
    [SerializeField] private ParticleSystem sparkles;

    [Header("Flash Settings")]
    [SerializeField] private float flashIntensity = 8f;   // ????? ??????? ???? ???????
    [SerializeField] private float idleIntensity = 2f;     // ??????? ???? ??? ????? ????
    [SerializeField] private float flashDuration = 0.15f;  // ???? ???? ?????? ?? ???
    [SerializeField] private float pulseSpeed = 2f;        // ???? ??? ????? ???? ??? ?? ???

    private Coroutine loopRoutine;

    private void Awake()
    {
        Hide(instant: true);
    }

    // ??? ?? ??? ??? ???? ?????? ?? ????? ???? ???????
    public void Show()
    {
        gameObject.SetActive(true);

        if (sparkles != null)
            sparkles.Play();

        if (loopRoutine != null)
            StopCoroutine(loopRoutine);

        loopRoutine = StartCoroutine(FlashThenPulse());
    }

    // ??? ?? ??? ??? ???? ?????? ?????? ?? ?? (???? ???? ???? ??? ???? ???)
    public void Hide(bool instant = false)
    {
        if (loopRoutine != null)
        {
            StopCoroutine(loopRoutine);
            loopRoutine = null;
        }

        if (instant)
        {
            if (glowLight != null) glowLight.intensity = 0f;
            gameObject.SetActive(false);
            return;
        }

        StartCoroutine(FadeOutAndDisable());
    }

    private IEnumerator FlashThenPulse()
    {
        // ????? ?: ??? ??? ?? ??? ??????? (???? "???????" ?? ??????)
        float t = 0f;
        while (t < flashDuration)
        {
            t += Time.deltaTime;
            if (glowLight != null)
                glowLight.intensity = Mathf.Lerp(0f, flashIntensity, t / flashDuration);
            yield return null;
        }

        // ????? ?: ?? ???? Hide ????? ???? ??? ?? ???????? ?? ?? ??? ?????? ????? ???
        while (true)
        {
            float pulse = (Mathf.Sin(Time.time * pulseSpeed) + 1f) * 0.5f; // ??? 0 ? 1
            if (glowLight != null)
                glowLight.intensity = Mathf.Lerp(idleIntensity, flashIntensity, pulse);

            yield return null;
        }
    }

    private IEnumerator FadeOutAndDisable()
    {
        float startIntensity = glowLight != null ? glowLight.intensity : 0f;
        float t = 0f;
        float fadeTime = 0.3f;

        while (t < fadeTime)
        {
            t += Time.deltaTime;
            if (glowLight != null)
                glowLight.intensity = Mathf.Lerp(startIntensity, 0f, t / fadeTime);
            yield return null;
        }

        gameObject.SetActive(false);
    }
}